// ─────────────────────────────────────────────────────────────────────────────
// app_relauncher.dart — إعادة تشغيل البرنامج على سطح المكتب
//
// لماذا إعادة تشغيل لا إعادة فتح القاعدة في مكانها؟
//   بعد «فتح قاعدة موجودة» تتغيّر **البيانات كلها**: المستخدمون والجلسة
//   والإعدادات. والجلسة الحالية تحمل مستخدماً من القاعدة السابقة قد لا يوجد
//   في الجديدة (أو يوجد بالمعرّف نفسه لشخصٍ آخر!). وإبطال المزوّدات واحداً
//   واحداً يترك حتماً ما يحمل قيمةً من العالم القديم.
//   أما النقل فالبيانات نفسها — فيكفيه تبديل المسار بلا إعادة تشغيل.
// ─────────────────────────────────────────────────────────────────────────────

import 'dart:io';

/// يُشغّل نسخةً جديدة من البرنامج ثم يُنهي هذه
///
/// ⚠️ **أغلق القاعدة قبل استدعائها** — النسخة الجديدة تفتح القاعدة فوراً،
///   وإن بقيت مفتوحةً هنا فاتصالان على الملف لحظةَ الانتقال.
///
/// إن تعذّر تشغيل النسخة الجديدة يُنهى البرنامج على أي حال — والمالك يفتحه
/// بيده فيقرأ المؤشّر الجديد. ولا يبقى مفتوحاً بقاعدةٍ مغلقة لا تعمل.
Future<Never> relaunchApp() async {
  try {
    await Process.start(
      Platform.resolvedExecutable,
      const [],
      mode: ProcessStartMode.detached,
    );
  } catch (_) {
    // يفتحه المالك بيده — راجع التعليق أعلاه
  }
  exit(0);
}
