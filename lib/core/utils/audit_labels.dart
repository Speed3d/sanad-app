// 🔴 **البلاغ (المالك 2026-08-30):** «في سجل المراجعة الفلاتر تظهر هكذا:
//   FISCAL_CLOSE · LOGOUT · LOGIN · DELETE · UPDATE · INSERT. وعند الضغط على
//   INSERT تظهر التفاصيل بأسمائها البرمجية مثل salary_payments و vouchers».
//
//   وهو محقّ: الشاشة كانت تعرض **ثوابت الكود كما هي**. والمالك يقرأ عربية،
//   ولا يلزمه أن يعرف أن `salary_payments` تعني «رواتب».
//
// ═══ لماذا ملف مستقلّ في `core` لا نصوص في الشاشة؟ ═══
//   الأسماء البرمجية تظهر في **ثلاثة مواضع** داخل الشاشة (شريحة الفلتر ·
//   بطاقة السجل · ورقة التفاصيل)، وستظهر في تصدير سجل التدقيق لاحقاً.
//   وترجمةٌ منسوخة ثلاث مرّات تُصحَّح في واحدة وتُنسى في اثنتين — وهي عائلة
//   الأعطال الأشيع في هذا المشروع.
//
// ═══ القاعدة: المجهول يُعرَض كما هو لا يُخفى ═══
//   أي عملية أو جدول بلا ترجمة يُعاد نصّه الأصلي. إخفاؤه أو استبداله بـ
//   «غير معروف» يُضيّع معلومةً حقيقية من **سجل رقابي** — وهو آخر ما يجوز
//   العبث به. والظهور بالإنجليزية تذكيرٌ بأن الترجمة ناقصة.
// ─────────────────────────────────────────────────────────────────────────────

/// تعريب أسماء العمليات والجداول في سجل التدقيق
abstract final class AuditLabels {
  // ── العمليات ─────────────────────────────────────────────────────────────

  /// كل أنواع العمليات المسجَّلة — بالترتيب الذي تظهر به شرائح الفلترة
  ///
  /// ⚠️ **السبعة عشر كلها** لا الستّة التي كانت معروضة: `AuditActions` يعرّف
  ///   سبعة عشر نوعاً، وكانت الشاشة تعرض ستّة فقط — فالأحد عشر الباقية
  ///   (اعتماد سلفة · إلغاؤها · النسخ الاحتياطي · الاستيراد · التحويل …)
  ///   تظهر تحت «الكل» بلا شريحة تصل إليها.
  static const List<String> allActions = [
    'INSERT',
    'UPDATE',
    'DELETE',
    'LOGIN',
    'LOGOUT',
    'TRANSFER',
    'ADVANCE_POST',
    'ADVANCE_CANCEL',
    'FISCAL_CLOSE',
    'FISCAL_REOPEN',
    'OPENING_BALANCE',
    'BACKUP_CREATE',
    'BACKUP_RESTORE',
    'CLOUD_UPLOAD',
    'EXCEL_IMPORT',
    'EXCEL_EXPORT',
    'PDF_EXPORT',
    'SETTING_CHANGED',
  ];

  static const Map<String, String> _actions = {
    'INSERT': 'إضافة',
    'UPDATE': 'تعديل',
    'DELETE': 'حذف',
    'LOGIN': 'دخول',
    'LOGOUT': 'خروج',
    'TRANSFER': 'تحويل',
    'ADVANCE_POST': 'اعتماد سلفة',
    'ADVANCE_CANCEL': 'إلغاء سلفة',
    'FISCAL_CLOSE': 'إقفال سنة',
    'FISCAL_REOPEN': 'إعادة فتح سنة',
    'OPENING_BALANCE': 'رصيد افتتاحي',
    'BACKUP_CREATE': 'نسخة احتياطية',
    'BACKUP_RESTORE': 'استعادة نسخة',
    'CLOUD_UPLOAD': 'نسخة إضافية',
    'EXCEL_IMPORT': 'استيراد إكسل',
    'EXCEL_EXPORT': 'تصدير إكسل',
    'PDF_EXPORT': 'تصدير PDF',
    'SETTING_CHANGED': 'تغيير إعداد',
  };

  /// اسم العملية بالعربية — أو النصّ الأصلي إن لم تُترجَم بعد
  static String action(String raw) =>
      _actions[raw.toUpperCase()] ?? raw;

  // ── الجداول ──────────────────────────────────────────────────────────────

  static const Map<String, String> _tables = {
    'users': 'المستخدمون',
    'vouchers': 'السندات',
    'treasuries': 'الخزائن',
    'employees': 'الموظفون',
    'departments': 'أقسام الموظفين', // Schema v8
    // ⚠️ التمييز مقصود: `cash_advances` سلفة **موظف** و`advances` سلفة
    //   **مشروع**. اللفظ العربي واحد، والخلط بينهما كلّفنا أعطالاً.
    'cash_advances': 'سلف الموظفين',
    'advances': 'سلف المشاريع',
    'salary_payments': 'الرواتب',
    'payroll_periods': 'كشوف الرواتب',
    'contractors': 'المقاولون',
    'partners': 'الشركاء',
    'fiscal_periods': 'السنوات المالية',
    'app_settings': 'الإعدادات',
    'attachments': 'المرفقات',
    'system': 'النظام',
  };

  /// اسم الجدول بالعربية — أو النصّ الأصلي إن لم يُترجَم بعد
  static String table(String raw) => _tables[raw.toLowerCase()] ?? raw;
}
