// treasury_state_guard.dart — حارس الخزينة المعطَّلة
//
// 🔴 **الثغرة التي أُغلقت (بلاغ المالك 2026-08-30):**
//   «يجب أن يكون هناك تحقّق: إذا عُطّلت الخزنة لا نستطيع تحويل مبلغ إليها
//   إلا بعد تفعيلها.»
//
//   وكان محقّاً: `is_active` عمودٌ موجود في `treasuries` منذ البداية، وله
//   مبدّل في الواجهة (`setTreasuryActive`) — **ولا يفحصه أي مسار كتابة**.
//   فالمال يدخل خزينةً أوقفها المالك بنفسه ويخرج منها، بلا اعتراض واحد.
//
//   وهو نفس صنف ع-٠٦: حقلٌ يُكتَب ولا يُقرأ — والميزة معطَّلة بصمت.
//
// ═══ لماذا خدمة مشتركة لا فحص في كل مستدعٍ؟ ═══
//   مسارات الكتابة **خمسة**: إنشاء سند · تعديله · طرفا التحويل · تسديد
//   الرواتب · اعتماد السلف. وستّة أعطال في تاريخ هذا المشروع وُلدت من
//   «كل بابٍ يعرف قاعدةً ويجهل الباقي». فالقاعدة تُكتَب مرّة، ويمرّ بها
//   الجميع — على نهج `BalanceGuard` و`FiscalPeriodGuard` تماماً.
//
// ═══ ما لا يحرسه هذا الحارس عمداً ═══
//   **القراءة والتقارير.** خزينةٌ عُطّلت بعد سنةٍ من العمل تبقى أرصدتها
//   وسنداتها ظاهرة في كل تقرير — وإلا اختفى مالٌ حقيقي من الدفاتر. التعطيل
//   يمنع **الحركة الجديدة** لا يمحو الماضي.
// ─────────────────────────────────────────────────────────────────────────────

import '../../data/database/app_database.dart';

/// حارس حالة الخزينة
class TreasuryStateGuard {
  const TreasuryStateGuard._();

  /// يتحقّق أن الخزينة موجودة ونشطة وغير محذوفة
  ///
  /// [db]         — قاعدة البيانات
  /// [treasuryId] — الخزينة المراد إدخال حركة عليها
  /// [action]     — وصف العملية بلغة المالك، يظهر في الرسالة
  ///                («التحويل إلى» · «الصرف من» · «القبض في»)
  ///
  /// يرمي [StateError] برسالة عربية تسمّي الخزينة وتقول ما يُفعَل لرفع المنع.
  static Future<void> ensureActive(
    AppDatabase db,
    int treasuryId, {
    required String action,
  }) async {
    final t = await db.treasuriesDao.getTreasuryById(treasuryId);

    // خزينة غير موجودة ليست مسؤولية هذا الحارس — المفتاح الأجنبي يمسكها،
    // ورميُ رسالتين مختلفتين لعلّة واحدة يُربك أكثر مما يفيد.
    if (t == null) return;

    if (t.isDeleted) {
      throw StateError(
        'الخزينة «${t.name}» محذوفة — لا يمكن $action خزينة محذوفة.',
      );
    }

    if (!t.isActive) {
      throw StateError(
        'الخزينة «${t.name}» **معطَّلة** — لا يمكن $action خزينة موقوفة.\n'
        'فعّلها أولاً من: الخزائن ← بطاقة الخزينة ← تفعيل.',
      );
    }
  }

  /// يحرس طرفَي التحويل معاً برسالة تميّز أيّهما المانع
  ///
  /// ⚠️ **الترتيب مقصود: المصدر أولاً.** لو فُحصت الوجهة أولاً لظهرت رسالة
  ///   عن خزينةٍ لم يصلها المال أصلاً، بينما المانع الحقيقي أن المال لا
  ///   يخرج من مصدره.
  static Future<void> ensureTransferAllowed(
    AppDatabase db, {
    required int fromTreasuryId,
    required int toTreasuryId,
  }) async {
    await ensureActive(db, fromTreasuryId, action: 'التحويل من');
    await ensureActive(db, toTreasuryId, action: 'التحويل إلى');
  }
}
