// ═══ لماذا نموذج **واحد** لستّة تقارير؟ ═══
//   التقارير الستّة (كشف الحساب · الملخّص اليومي · تقرير الفترة · سلف
//   المشاريع · حسب البند · المستحقات) تختلف في **مصادرها** لا في **شكلها**:
//   كلها عنوانٌ وبطاقات ملخّص وجدول صفوف. فستّة مولّدات PDF تعني ستّ نسخ من
