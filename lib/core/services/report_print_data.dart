/// سطر ملخّص في ترويسة التقرير — «إجمالي الصرف: ١٬٢٠٠٬٠٠٠ د.ع»
typedef ReportSummaryLine = ({String label, String value});

/// بيان تقرير جدوليّ جاهز للطباعة
class ReportTableData {
  const ReportTableData({
    required this.title,
    required this.columns,
    required this.rows,
    this.subtitle = '',
    this.summary = const [],
    this.footerNote,
    this.landscape = false,
    this.numericColumns = const {},
  });

  /// عنوان التقرير — «كشف حساب: خزنة بغداد»
  final String title;

  /// سطر الفلاتر الفعّالة — «من 2026/01/01 إلى 2026/03/31 · المشروع: البصرة»
  ///
  /// ⚠️ **ليس تزييناً.** تقريرٌ مطبوع بلا فلاتره ورقةٌ لا يُعرف ما تمثّله بعد
  ///   أسبوع، ولا يمكن إعادة إنتاجها ولا مقارنتها بغيرها.
  final String subtitle;

  /// عناوين الأعمدة — بالترتيب نفسه الذي في [rows]
  final List<String> columns;

  /// الصفوف — **نصوص منسَّقة مسبقاً**، وطول كل صفّ = طول [columns]
  final List<List<String>> rows;

  /// بطاقات المجاميع أعلى الجدول
  final List<ReportSummaryLine> summary;

  /// ملاحظة أسفل الجدول — قرارٌ محاسبي يفسّر الأرقام
  ///
  /// مثال: «التحويلات بين الخزائن ليست مصروفاً» — بدونها يظنّ القارئ أن
  /// المجموع ناقص، فيفقد الثقة بالتقرير كلّه.
  final String? footerNote;

  /// ورقة عرضيّة — للجداول التي تتجاوز ستّة أعمدة
  final bool landscape;

  /// فهارس الأعمدة التي تحمل **أرقاماً** لا نصّاً
  ///
  /// تُستعمَل في تصدير Excel وحده: الخليّة المُعلَنة رقمية تُكتَب
  /// `DoubleCellValue` بتنسيق آلاف، فيستطيع المالك **جمعها وفرزها**
  /// والدخول بها في معادلة.
  ///
  /// ⚠️ بدونها يُصدَّر كل شيء نصّاً — ففرزُ عمود مبالغ يأتي أبجدياً:
  ///   ٩ بعد ٨٠٠٬٠٠٠. والـPDF لا يتأثّر بها إطلاقاً.
  final Set<int> numericColumns;

  bool get isEmpty => rows.isEmpty;

  /// عدد الصفوف — يُعرَض في الذيل ليُعرف أن الورقة كاملة لا مبتورة
  int get rowCount => rows.length;
}
