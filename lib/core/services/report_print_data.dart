// ═══ القاعدة الحاكمة: الصفوف **منسَّقة مسبقاً** ═══
//   `rows` نصوصٌ جاهزة لا أرقام. المستند **لا يحسب ولا ينسّق ولا يحوّل عملة**
//   — يرسم ما يُعطى فقط. لأن التنسيق قرار محاسبي (الدينار بلا كسور، الدولار
//   بكسرين، العملتان لا تُجمعان) ومكانه طبقةُ من يعرف المعنى لا من يرسم.
