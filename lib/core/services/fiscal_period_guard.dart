//   فحص موحّد يمنع أي كتابة (إنشاء / تعديل / حذف / اعتماد) داخل فترة مالية
//   غير نشطة.
//
// لماذا؟ (إصلاح تدقيق 2026-08-06)
//   الفترة المُقفَلة (frozen) تمثّل بيانات محاسبية مُجمَّدة أُغلقت السنة عليها.
//   الكتابة فيها تغيّر أرصدة تاريخية بعد إقفالها، فتتناقض التقارير المطبوعة
//   سابقاً مع ما يعرضه النظام لاحقاً — وهو خلل يصعب اكتشافه بعد وقوعه.
//
// لماذا خدمة مشتركة وليس تابعاً خاصاً في كل مستودع؟
//   كان هذا الحارس تابعاً خاصاً داخل VoucherRepository وحده. مع إضافة مستودع
//   السلف صار يحتاجه مستودعان، ونسخه مرتين يعني أن تصحيح صياغة الرسالة أو
//   إضافة حالة جديدة لاحقاً قد يُطبَّق في مكان ويُنسى في الآخر. الخدمة
//   المشتركة تجعل القاعدة واحدة لا تتفرّع — على نهج BalanceGuard نفسه.
// ─────────────────────────────────────────────────────────────────────────────

import '../../data/database/app_database.dart';

/// حارس الفترة المالية
class FiscalPeriodGuard {
  const FiscalPeriodGuard._();

  /// يتحقق أن الفترة المالية نشطة وتقبل الكتابة
  ///
  /// [db]             — قاعدة البيانات
  /// [fiscalPeriodId] — الفترة المراد الكتابة فيها
  ///
  /// يرمي [StateError] برسالة عربية إذا كانت الفترة مُقفَلة.
  /// لا يفعل شيئاً إذا كانت نشطة أو غير موجودة (فترة محذوفة ليست مسؤوليته).
  static Future<void> ensureActive(
    AppDatabase db,
    int fiscalPeriodId,
  ) async {
    final period = await db.fiscalPeriodsDao.getPeriodById(fiscalPeriodId);
    if (period != null && period.status != 'active') {
      throw StateError(
        'الفترة المالية "${period.name}" مُقفَلة — لا يمكن تعديل أو إضافة '
        'سندات فيها. أعد فتح الفترة أولاً إذا لزم الأمر.',
      );
    }
  }
}
