// **لماذا في `core` لا في `domain` ولا في جدول القاعدة؟**
//   لأن الثلاثة تحتاجها: قيد `CHECK` على الجدول (`data`)، والنموذج
//   (`domain`)، وشرائح الفلترة والتسميات (`presentation`). و`core` وحدها
//   متاحة للجميع بلا عكس اتجاه الاعتماد.
//
// ⚠️ **والتسمية العربية هنا لا في الشاشة**: ترجمةٌ منسوخة في ثلاث شاشات
//   تُصحَّح في واحدة وتُنسى في اثنتين — وهو بالضبط ما دفعنا إلى
//   `audit_labels.dart` في الدفعة ب (ع-٤٧).
// ─────────────────────────────────────────────────────────────────────────────

/// حالات الموظف — مصدر الحقيقة الوحيد
abstract final class EmployeeStatus {
  /// على رأس عمله — الحالة الافتراضية
  static const String active = 'active';

  /// انتهت خدمته — لا يدخل كشوف الرواتب **الجديدة**، وتاريخه محفوظ كاملاً
  static const String terminated = 'terminated';

  /// في إجازة — يبقى في الكشوف، والقرار في راتبه للمالك
  ///
  /// 📌 **ولا يُستبعَد تلقائياً** عن قصد: الإجازة قد تكون مدفوعة وقد لا
  ///   تكون، والبرنامج لا يعرف أيّهما. استبعادُه بافتراضٍ يحرم موظفاً من
  ///   راتبه بصمت — وإظهاره بحالته المكتوبة يترك القرار لمن يملكه.
  static const String leave = 'leave';

  /// كل الحالات المعروفة — يطابق قيد CHECK في القاعدة
  static const List<String> all = [active, terminated, leave];

  /// التسمية العربية
  ///
  /// ⚠️ **والمجهول يُعرَض كما هو لا يُخفى** (درس ب-٥): قيمةٌ لا ترجمة لها
  ///   تظهر بنصّها الأصلي فيُعرف أن الترجمة ناقصة، بدل أن يختفي الصفّ.
  static String label(String status) => switch (status) {
        active => 'حالي',
        terminated => 'منتهية خدمته',
        leave => 'في إجازة',
        _ => status,
      };

  /// هل يدخل هذا الموظف كشوف الرواتب الجديدة؟
  ///
  /// منتهي الخدمة وحده يُستبعَد — راجع [leave] لسبب بقاء المُجاز.
  static bool joinsNewPayroll(String status) => status != terminated;
}
