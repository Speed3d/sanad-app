// ─────────────────────────────────────────────────────────────────────────────
// attachments_table.dart — مرفقات السلف والسندات (Schema v6)
//
// **المشكلة التي يحلّها:**
//   الفاتورة الورقية والوصل وصورة العقد هي الدليل المادّي على السند. كانت
//   تُحفَظ في مجلدات متفرّقة على القرص بلا رابط بالسند، فيصعب إيجادها عند
//   المراجعة — أو تضيع مع أول إعادة تنظيم للمجلدات.
//
// ═══ القرار المعماري الأهمّ: المسار **نسبي** لا مطلق ═══
//
//   نُخزّن `relative_path` = «2026/سلفة-23-البصرة/فاتورة.pdf»
//   ولا نُخزّن  «D:\SanadFiles\2026\سلفة-23-البصرة\فاتورة.pdf»
//
//   **لماذا؟** المسار المطلق يكسر كل الروابط عند:
//     • نقل مجلد المرفقات إلى قرص آخر
//     • تغيّر حرف القرص (D: → E:) — يحدث تلقائياً عند تركيب قرص جديد
//     • فتح النسخة الاحتياطية على جهاز ثانٍ (الماك مثلاً)
//   بالمسار النسبي يكفي تعديل **مفتاح إعداد واحد** (جذر المرفقات) فتعود كل
//   الروابط سليمة دفعةً واحدة.
//
// ═══ لماذا لا نخزّن الملف نفسه في قاعدة البيانات؟ ═══
//   جدول `app_blobs` مناسب لشعار بحجم كيلوبايتات. أما فواتير PDF بعشرات
//   الميغابايتات فتُضخّم ملف القاعدة، وتُبطئ كل نسخة احتياطية مشفَّرة، وتجعل
//   استعادتها عملية ثقيلة. الملفات على القرص والقاعدة تحمل **الفهرس** فقط.
// ─────────────────────────────────────────────────────────────────────────────

import 'package:drift/drift.dart';

/// جدول مرفقات السلف والسندات
class Attachments extends Table {
  // المعرّف الأساسي
  IntColumn get id => integer().autoIncrement()();

  // ── الكيان المرتبط ────────────────────────────────────────────────────────

  /// نوع الكيان: 'advance' (سلفة مشروع) | 'voucher' (سند)
  ///
  /// ربط متعدّد الأشكال بدل جدولَي مرفقات منفصلين: المرفق سلوكه واحد مهما
  /// كان صاحبه، وفصله يعني تكرار كل استعلام ودالة مرّتين.
  TextColumn get entityType => text().named('entity_type')();

  /// معرّف الكيان — **بلا مفتاح خارجي عمداً**
  ///
  /// لأن العمود يشير إلى جدولين مختلفين حسب `entity_type`، ولا يدعم SQLite
  /// مفتاحاً خارجياً شرطياً. النظافة مسؤولية طبقة الحذف: راجع
  /// `AttachmentsDao.deleteForEntity`.
  IntColumn get entityId => integer().named('entity_id')();

  // ── الملف ─────────────────────────────────────────────────────────────────

  /// اسم الملف كما اختاره المستخدم — للعرض فقط
  TextColumn get fileName => text().named('file_name').withLength(min: 1, max: 255)();

  /// المسار **النسبي** من جذر المرفقات — يستعمل `/` دائماً
  ///
  /// نوحّد الفاصل على `/` حتى على ويندوز: القاعدة قد تُفتَح على الماك،
  /// وفاصل ويندوز `\` يصير هناك جزءاً من اسم الملف لا فاصلاً.
  TextColumn get relativePath =>
      text().named('relative_path').withLength(min: 1, max: 500)();

  /// نوع المحتوى: 'application/pdf' · 'image/jpeg' …
  TextColumn get mimeType =>
      text().named('mime_type').withDefault(const Constant(''))();

  /// حجم الملف بالبايت — لعرضه وللتحقق من سلامة النسخ
  IntColumn get sizeBytes =>
      integer().named('size_bytes').withDefault(const Constant(0))();

  /// بصمة SHA-256 للمحتوى
  ///
  /// غرضها الأول كشف إرفاق **نفس الملف مرّتين** على الكيان نفسه، والثاني
  /// التحقّق أن الملف على القرص لم يُستبدَل أو يتلف منذ إرفاقه.
  TextColumn get sha256 =>
      text().named('sha256').withDefault(const Constant(''))();

  // ── الأثر ─────────────────────────────────────────────────────────────────

  /// من أرفق الملف
  IntColumn get uploadedByUserId =>
      integer().named('uploaded_by_user_id').nullable()();

  /// ملاحظة اختيارية على المرفق (وصف محتواه)
  TextColumn get notes => text().withDefault(const Constant(''))();

  /// وقت الإرفاق
  DateTimeColumn get createdAt =>
      dateTime().named('created_at').withDefault(currentDateAndTime)();

  /// قيود على مستوى الجدول (دفاع في العمق)
  @override
  List<String> get customConstraints => [
        // نوع كيان غير معروف يعني مرفقاً يتيماً لا تصل إليه أي شاشة
        "CHECK (entity_type IN ('advance', 'voucher'))",
        // مرفقان بنفس المسار النسبي يعنيان أن أحدهما يشير لملف ليس له
        'UNIQUE (relative_path)',
      ];
}
