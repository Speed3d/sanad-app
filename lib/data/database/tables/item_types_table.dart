// ─────────────────────────────────────────────────────────────────────────────
// item_types_table.dart — قائمة أنواع البنود (الفلاتر) الموحّدة
//
// المشكلة التي يحلها هذا الجدول:
//   كانت أنواع البنود قوائم ثابتة (const) مبعثرة داخل ملفات الشاشات:
//   قائمة في voucher_sarf_screen.dart وأخرى في voucher_kabd_screen.dart.
//   ولأن الاستيراد من الإكسل يقبل أي نص حر، كانت «كهربائيات» و«كهربائيه»
//   و«الكهربائيات» تصبح ثلاثة بنود مختلفة، فتتفتّت التقارير بلا أن يلاحظ أحد.
//
// الحل:
//   مصدر واحد للحقيقة في قاعدة البيانات، يديره المالك من الإعدادات
//   (إضافة / تعطيل / إعادة ترتيب)، وتقرأ منه كل الشاشات وشاشة مراجعة المسودة.
//
// لماذا التعطيل (is_active) بدل الحذف؟
//   بند مستعمَل في سندات قديمة لا يجوز حذفه — التقارير التاريخية ستفقد معناها.
//   التعطيل يُخفيه من قوائم الاختيار الجديدة ويُبقي السجلات القديمة سليمة.
// ─────────────────────────────────────────────────────────────────────────────

import 'package:drift/drift.dart';

/// جدول أنواع البنود الموحّدة
class ItemTypes extends Table {
  // المعرّف الأساسي
  IntColumn get id => integer().autoIncrement()();

  // اسم البند بالعربية — فريد لمنع التكرار (مثل: 'كهربائيات')
  TextColumn get name => text().withLength(min: 1, max: 60).unique()();

  // لأي نوع سند يصلح هذا البند:
  //   'sarf' — بنود الصرف (كهربائيات، راتب، إيجار…)
  //   'kabd' — بنود القبض (رأس مال، دفعة عميل…)
  //   'both' — يصلح للاثنين
  TextColumn get kind => text().withDefault(const Constant('sarf'))();

  // هل يظهر في قوائم الاختيار الجديدة؟
  BoolColumn get isActive =>
      boolean().named('is_active').withDefault(const Constant(true))();

  // ترتيب العرض — الأصغر أولاً، لوضع البنود الأكثر استعمالاً في الأعلى
  IntColumn get sortOrder =>
      integer().named('sort_order').withDefault(const Constant(0))();

  /// قيود على مستوى الجدول (دفاع في العمق)
  @override
  List<String> get customConstraints => [
        "CHECK (kind IN ('sarf', 'kabd', 'both'))",
      ];
}
