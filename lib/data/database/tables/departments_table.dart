// **الحاجة التي يسدّها** (بلاغ المالك 2026-08-30 · الدفعة د):
//   «أريد الموظفين مرتّبين بأقسام: مهندسون ١–٧ · فنيون ٨–١٩ · سواق ٢٠–٣٥،
//   وأن أرتّبهم بيدي داخل كل قسم.»
//
//   وكانت قائمة الموظفين تُرتَّب بـ`id` — أي **بترتيب الإدخال**. فمن يُضاف
//   اليوم يقع آخر القائمة مهما كان موقعه في الشركة، ولا سبيل إلى تغيير ذلك.
//
// ═══ لماذا جدولٌ لا نصٌّ في عمود على الموظف؟ ═══
//   لأن اسم القسم يُكتَب بيد الإنسان، و«فنيون» و«الفنيون» و«فنيين» تصير
//   ثلاثة أقسام بلا أن يلاحظ أحد — وهي **عين العلّة** التي أنشأت
//   `item_types` (راجع رأس `item_types_table.dart`). والجدول يجعل إعادة
//   التسمية عمليةً واحدة تصل كل من ينتمي إليه.
//
// ═══ الترتيب على مستويين لا مستوى واحد ═══
//   للقسم `sort_order` وللموظف `sort_order` **داخل قسمه**. فالعرض يقع:
//       ترتيب القسم ← ترتيب الموظف داخله ← الاسم
//   وهذا يُنتج تسلسل المالك تماماً (مهندسون ١–٧ ثم فنيون ٨–١٩)، بينما
//   الترتيب العالمي الواحد يفرض إعادة ترقيم **كل** الموظفين عند كل نقلة.
// ─────────────────────────────────────────────────────────────────────────────

import 'package:drift/drift.dart';

/// جدول أقسام الموظفين
class Departments extends Table {
  /// المعرّف الأساسي
  IntColumn get id => integer().autoIncrement()();

  /// اسم القسم — «مهندسون» · «فنيون» · «سواق»
  ///
  /// ⚠️ **بلا `.unique()` على مستوى العمود** رغم أن التكرار ممنوع: الحذف
  ///   ناعم (القانون ٨)، فقيدٌ مطلق يمنع إعادة إنشاء قسمٍ حُذف بالاسم نفسه
  ///   إلى الأبد. الفرادة تقع في **فهرس جزئي** على غير المحذوف — راجع
  ///   `_createIndexes` في `app_database.dart`.
  TextColumn get name => text().withLength(min: 1, max: 60)();

  /// ترتيب القسم في القائمة — الأصغر أولاً
  IntColumn get sortOrder =>
      integer().named('sort_order').withDefault(const Constant(0))();

  /// وقت الإنشاء
  DateTimeColumn get createdAt =>
      dateTime().named('created_at').withDefault(currentDateAndTime)();

  /// حذف ناعم — القانون ٨
  ///
  /// قسمٌ حُذف يبقى موظفوه يشيرون إليه بـ`department_id`، فيُعرَضون تحت
  /// «بلا قسم» بدل أن يختفوا أو يشيروا إلى معرّفٍ لا وجود له.
  BoolColumn get isDeleted =>
      boolean().named('is_deleted').withDefault(const Constant(false))();
}
